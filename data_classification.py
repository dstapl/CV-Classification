def setup_Lomb(timeseries, magnitude_series, cv_object, errors):
    """Creates a Lomb-Scargle object with the provided settings

    Returns:
        - ls: Periodogram settings (LombScargle object)
        - factor: Resolution of the periodogram based on sampling frequency and expected orbit
        - max_freq: Maximum frequency based on the nyquist frequency
    """
    # Generate time series
    # Assuming continuous sampling

    # Calculate Lomb-Scargle periodogram
    # Factor is the sampling frequency = factor*the nyquist frequency
    t_exp = timeseries[1] - timeseries[0]
    if t_exp.unit == u.dimensionless_unscaled:
        t_exp = t_exp.value
    has_units = hasattr(t_exp, "unit")

    sampling_freq = 1/t_exp
    
    period = cv_object.period.value
    if has_units:
        period = period * t_exp.unit

    nyquist_freq = 0.5 * 1/period

    factor = sampling_freq / nyquist_freq
    if has_units:
        factor = factor.to(u.dimensionless_unscaled).value

    # TODO: Set pre-factor
    # pre-factor should = 1, but periodogram is an approximation so leaving room for errors
    max_freq = 1e+1*nyquist_freq
    if has_units:
        max_freq = max_freq.to(1/u.s)

    ls = LombScargle(timeseries, magnitude_series, errors, normalization = "standard")
    return (ls, factor, max_freq) 
